"""Append-only, hash-chained, Ed25519-signed turn journal for one cloud task.

The signing key is generated by ``open`` inside the task, kept outside the
repository with owner-only permissions and destroyed by ``seal``. A cloud
environment's install script runs once and its filesystem is reused by later
tasks, so a key must never be created there.

A signature binds the records to this task's key and makes later edits
detectable. It does not make the agent's statements true: everything in a
journal is *reported* by the agent.
"""
from __future__ import annotations

import base64
import hashlib
import json
import os
import platform
import secrets
import subprocess
import sys
import time
from contextlib import contextmanager
from datetime import UTC, datetime
from pathlib import Path

from cryptography.hazmat.primitives import serialization
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PrivateKey

from . import __version__
from .scan import scan

JOURNAL_FORMAT = "integrity-cloud-journal/v1"
BUNDLE_FORMAT = "integrity-cloud-bundle/v1"
RECORD_TYPES = ("open", "turn_open", "event", "observation", "turn_close", "seal")
EVENT_KINDS = ("task", "thought", "concept", "action")
NO_EVENT_REASONS = (
    "no-durable-state-change", "read-only", "repetition", "social-response", "user-cancelled",
)
OUTCOMES = ("events", "no-event")
MAX_SUMMARY = 2000
MAX_INTENT = 500
MAX_LABEL = 200
MAX_TAGS = 20
MAX_TAG = 64
MAX_DETAILS_BYTES = 16 * 1024
MAX_FIELD = 2000
MAX_RECORDS = 10_000
MAX_BUNDLE_BYTES = 8 * 1024 * 1024
JOURNAL_NAME = "journal.jsonl"
SIGNER_NAME = "signer.bin"
CAPSULE_NAME = "capsule.json"
SEALED_DIR = "sealed"


class JournalError(Exception):
    """A refused journal operation; the message is safe to show the agent."""


def canonical(value: object) -> bytes:
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=False,
                      allow_nan=False).encode("utf-8")


def digest(data: bytes) -> str:
    return "sha256:" + hashlib.sha256(data).hexdigest()


def record_hash(record: dict) -> str:
    return digest(canonical(record))


def signing_bytes(record: dict) -> bytes:
    return canonical({k: v for k, v in record.items() if k != "sig"})


def utc_now() -> str:
    return datetime.now(UTC).strftime("%Y-%m-%dT%H:%M:%SZ")


def b64(data: bytes) -> str:
    return base64.urlsafe_b64encode(data).decode("ascii").rstrip("=")


def unb64(text: str) -> bytes:
    return base64.urlsafe_b64decode(text + "=" * (-len(text) % 4))


def default_home() -> Path:
    configured = os.environ.get("INTEGRITY_CLOUD_HOME")
    return Path(configured) if configured else Path.home() / ".integrity-cloud"


def _bounded(text: str | None, limit: int, name: str) -> str | None:
    if text is None:
        return None
    if not isinstance(text, str):
        raise JournalError(f"{name} must be text")
    text = text.strip()
    if len(text) > limit:
        raise JournalError(f"{name} is longer than {limit} characters")
    return text


def _tags(tags: list[str] | None) -> list[str]:
    tags = [t.strip() for t in (tags or []) if t and t.strip()]
    if len(tags) > MAX_TAGS or any(len(t) > MAX_TAG for t in tags):
        raise JournalError(f"at most {MAX_TAGS} tags of at most {MAX_TAG} characters")
    return tags


def _refuse_secrets(body: dict) -> None:
    findings = scan(body)
    if findings:
        where = ", ".join(sorted({f"{f['path']}:{f['finding']}" for f in findings}))
        raise JournalError("refused secret-like content (rephrase without the value): " + where)


def git_head(cwd: Path | None = None) -> str | None:
    try:
        result = subprocess.run(["git", "rev-parse", "HEAD"], cwd=cwd, capture_output=True,
                                text=True, timeout=10, check=False)
    except (OSError, subprocess.TimeoutExpired):
        return None
    head = result.stdout.strip()
    return head if result.returncode == 0 and len(head) in (40, 64) else None


class Journal:
    """The single open journal under one home directory."""

    def __init__(self, home: Path | None = None):
        self.home = Path(home) if home else default_home()
        self.path = self.home / JOURNAL_NAME
        self.signer_path = self.home / SIGNER_NAME

    # -- storage -----------------------------------------------------------
    @contextmanager
    def _lock(self):
        self.home.mkdir(parents=True, exist_ok=True)
        lock = self.home / ".lock"
        deadline = time.monotonic() + 10
        while True:
            try:
                fd = os.open(lock, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
                break
            except FileExistsError:
                if time.monotonic() > deadline:
                    raise JournalError("journal is locked by another integrity-cloud process")
                time.sleep(0.05)
        try:
            yield
        finally:
            os.close(fd)
            lock.unlink(missing_ok=True)

    def records(self) -> list[dict]:
        if not self.path.is_file():
            return []
        rows = []
        for line in self.path.read_text(encoding="utf-8").splitlines():
            if line.strip():
                rows.append(json.loads(line))
        return rows

    def state(self) -> dict:
        rows = self.records()
        state = {"home": str(self.home), "open": bool(rows), "journal_id": None, "seq": -1,
                 "head": "genesis", "turn": 0, "open_turn": None, "turn_events": [],
                 "sealed": False, "events": 0, "observations": 0, "turns": 0}
        for row in rows:
            state["journal_id"] = row["journal_id"]
            state["seq"] = row["seq"]
            state["head"] = record_hash(row)
            kind = row["type"]
            if kind == "turn_open":
                state["turn"] = row["body"]["turn"]
                state["open_turn"] = row["body"]["turn"]
                state["turn_events"] = []
            elif kind == "event":
                state["events"] += 1
                state["turn_events"].append(record_hash(row))
            elif kind == "observation":
                state["observations"] += 1
            elif kind == "turn_close":
                state["turns"] += 1
                state["open_turn"] = None
                state["turn_events"] = []
            elif kind == "seal":
                state["sealed"] = True
        return state

    def _signer(self) -> Ed25519PrivateKey:
        if not self.signer_path.is_file():
            raise JournalError("no signing key: the journal is sealed or was never opened")
        return Ed25519PrivateKey.from_private_bytes(self.signer_path.read_bytes())

    def _write(self, record: dict) -> None:
        line = json.dumps(record, sort_keys=True, ensure_ascii=False) + "\n"
        with open(self.path, "a", encoding="utf-8", newline="\n") as handle:
            handle.write(line)
            handle.flush()
            os.fsync(handle.fileno())

    def _append(self, state: dict, kind: str, body: dict) -> dict:
        if state["seq"] + 1 >= MAX_RECORDS:
            raise JournalError(f"journal is full ({MAX_RECORDS} records)")
        record = {"v": 1, "journal_id": state["journal_id"], "seq": state["seq"] + 1,
                  "prev": state["head"], "ts_utc": utc_now(), "type": kind, "body": body}
        record["sig"] = b64(self._signer().sign(signing_bytes(record)))
        self._write(record)
        return record

    def _require_live(self, state: dict) -> None:
        if not state["open"]:
            raise JournalError("no journal is open: run `integrity-cloud open` first")
        if state["sealed"]:
            raise JournalError("the journal is sealed; open a new one for new work")

    # -- operations ----------------------------------------------------------
    def open(self, *, capsule: dict | None = None, nonce: str | None = None,
             label: str | None = None, harness: str = "codex-cloud",
             base_commit: str | None = None) -> dict:
        with self._lock():
            state = self.state()
            if state["open"] and not state["sealed"]:
                raise JournalError(f"journal {state['journal_id']} is still open; seal it first")
            if state["sealed"]:
                archive = self.home / SEALED_DIR
                archive.mkdir(exist_ok=True)
                self.path.replace(archive / f"{state['journal_id']}.jsonl")
            if capsule is not None:
                if nonce is not None and nonce != capsule["nonce"]:
                    raise JournalError("--nonce differs from the capsule nonce")
                nonce = capsule["nonce"]
                (self.home / CAPSULE_NAME).write_text(
                    json.dumps(capsule, ensure_ascii=False, indent=2), encoding="utf-8")
            key = Ed25519PrivateKey.generate()
            raw = key.private_bytes(serialization.Encoding.Raw, serialization.PrivateFormat.Raw,
                                    serialization.NoEncryption())
            fd = os.open(self.signer_path, os.O_CREAT | os.O_EXCL | os.O_WRONLY, 0o600)
            with os.fdopen(fd, "wb") as handle:
                handle.write(raw)
            public = key.public_key().public_bytes(serialization.Encoding.Raw,
                                                   serialization.PublicFormat.Raw)
            body = {
                "format": JOURNAL_FORMAT,
                "public_key": b64(public),
                "harness": _bounded(harness, MAX_LABEL, "harness"),
                "label": _bounded(label, MAX_LABEL, "label"),
                "nonce": _bounded(nonce, MAX_LABEL, "nonce"),
                "capsule_sha256": capsule["sha256"] if capsule else None,
                "base_commit": base_commit if base_commit is not None else git_head(),
                "tool": {"name": "integrity-cloud", "version": __version__},
                "runtime": {"python": platform.python_version(), "platform": sys.platform},
            }
            _refuse_secrets(body)
            state = {"journal_id": secrets.token_hex(16), "seq": -1, "head": "genesis"}
            return self._append(state, "open", body)

    def turn_open(self, intent: str, *, implicit: bool = False) -> dict:
        with self._lock():
            state = self.state()
            self._require_live(state)
            if state["open_turn"] is not None:
                raise JournalError(f"turn {state['open_turn']} is still open; close it first")
            body = {"turn": state["turn"] + 1, "intent": _bounded(intent, MAX_INTENT, "intent"),
                    "implicit": implicit}
            if not body["intent"]:
                raise JournalError("intent is required")
            _refuse_secrets(body)
            return self._append(state, "turn_open", body)

    def event(self, kind: str, summary: str, *, tags: list[str] | None = None,
              details: dict | None = None, action: dict | None = None) -> dict:
        if kind not in EVENT_KINDS:
            raise JournalError("kind must be one of " + ", ".join(EVENT_KINDS))
        summary = _bounded(summary, MAX_SUMMARY, "summary")
        if not summary:
            raise JournalError("summary is required")
        details = details or {}
        if not isinstance(details, dict) or len(canonical(details)) > MAX_DETAILS_BYTES:
            raise JournalError(f"details must be a JSON object under {MAX_DETAILS_BYTES} bytes")
        body = {"kind": kind, "summary": summary, "tags": _tags(tags), "details": details}
        if kind == "action":
            action = {k: _bounded(v, MAX_FIELD, k) if isinstance(v, str) else v
                      for k, v in (action or {}).items() if v is not None}
            if not action.get("target") or not action.get("result"):
                raise JournalError("an action event needs --target and --result")
            body["action"] = action
        elif action:
            raise JournalError("--target/--command/--result belong to kind=action")
        _refuse_secrets(body)
        with self._lock():
            state = self.state()
            self._require_live(state)
        if state["open_turn"] is None:
            self.turn_open("(implicit turn opened by an event)", implicit=True)
        with self._lock():
            state = self.state()
            body["turn"] = state["open_turn"]
            return self._append(state, "event", body)

    def observation(self, source: str, *, tool_name: str | None = None,
                    input_sha256: str | None = None, exit_code: int | None = None,
                    turn_ref: str | None = None) -> dict:
        body = {"source": _bounded(source, MAX_LABEL, "source"),
                "tool_name": _bounded(tool_name, MAX_LABEL, "tool_name"),
                "input_sha256": input_sha256, "exit_code": exit_code,
                "turn_ref": _bounded(turn_ref, MAX_LABEL, "turn_ref")}
        _refuse_secrets(body)
        with self._lock():
            state = self.state()
            self._require_live(state)
            body["turn"] = state["open_turn"]
            return self._append(state, "observation", body)

    def turn_close(self, outcome: str, *, reason: str | None = None) -> dict:
        if outcome not in OUTCOMES:
            raise JournalError("outcome must be events or no-event")
        with self._lock():
            state = self.state()
            self._require_live(state)
            if state["open_turn"] is None:
                raise JournalError("no turn is open")
            events = list(state["turn_events"])
            if outcome == "events":
                if reason:
                    raise JournalError("outcome=events takes no reason")
                if not events:
                    raise JournalError("outcome=events but this turn recorded no events")
            else:
                if events:
                    raise JournalError("this turn recorded events; close it with outcome=events")
                if reason not in NO_EVENT_REASONS:
                    raise JournalError("no-event needs --reason " + "|".join(NO_EVENT_REASONS))
            body = {"turn": state["open_turn"], "outcome": outcome, "events": events,
                    "no_event_reason": reason if outcome == "no-event" else None}
            return self._append(state, "turn_close", body)

    def seal(self, out: str | Path) -> dict:
        """Seal and write the bundle; a trailing slash or a directory means <id>.json in it."""
        with self._lock():
            state = self.state()
            self._require_live(state)
            if state["open_turn"] is not None:
                raise JournalError(f"turn {state['open_turn']} is still open; close it first")
            body = {"records": state["seq"] + 1, "turns": state["turns"],
                    "events": state["events"], "observations": state["observations"],
                    "signer_destroyed": True}
            self._append(state, "seal", body)
            # Best-effort destruction: overwrite, then unlink. This is a claim
            # the agent reports, not something a verifier can observe.
            size = self.signer_path.stat().st_size
            with open(self.signer_path, "r+b") as handle:
                handle.write(b"\0" * size)
                handle.flush()
                os.fsync(handle.fileno())
            self.signer_path.unlink()
            records = self.records()
        bundle = {"format": BUNDLE_FORMAT, "journal_id": records[0]["journal_id"],
                  "public_key": records[0]["body"]["public_key"], "records": records}
        raw = str(out)
        out = Path(out)
        if out.is_dir() or raw.endswith(("/", os.sep)):
            out = out / f"{bundle['journal_id']}.json"
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(json.dumps(bundle, ensure_ascii=False, indent=1, sort_keys=True) + "\n",
                       encoding="utf-8", newline="\n")
        return {"bundle": str(out), "journal_id": bundle["journal_id"],
                "head": record_hash(records[-1]), **body}
